-- PaySim schema. Owned by Flyway; Hibernate only validates it.

CREATE TABLE payments (
    id                 UUID           PRIMARY KEY,
    customer_reference VARCHAR(64)    NOT NULL,
    order_reference    VARCHAR(64)    NOT NULL,
    amount             NUMERIC(19, 2) NOT NULL,
    currency           VARCHAR(3)     NOT NULL,
    description        VARCHAR(255),
    status             VARCHAR(20)    NOT NULL,
    decline_reason     VARCHAR(64),
    created_at         TIMESTAMPTZ    NOT NULL,
    updated_at         TIMESTAMPTZ    NOT NULL,
    refunded_at        TIMESTAMPTZ,
    version            BIGINT         NOT NULL DEFAULT 0,

    CONSTRAINT ck_payments_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_payments_currency_format CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_payments_status CHECK (status IN ('SUCCEEDED', 'DECLINED', 'REFUNDED')),
    CONSTRAINT ck_payments_decline_reason CHECK (
        (status = 'DECLINED' AND decline_reason IS NOT NULL) OR
        (status <> 'DECLINED' AND decline_reason IS NULL)),
    CONSTRAINT ck_payments_refunded_at CHECK ((status = 'REFUNDED') = (refunded_at IS NOT NULL))
);

CREATE INDEX ix_payments_created_at      ON payments (created_at DESC, id DESC);
CREATE INDEX ix_payments_status_created  ON payments (status, created_at DESC);
CREATE INDEX ix_payments_order_reference ON payments (order_reference);
CREATE INDEX ix_payments_customer_ref    ON payments (customer_reference);

CREATE TABLE payment_audit_events (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id      UUID         NOT NULL REFERENCES payments (id),
    event_type      VARCHAR(40)  NOT NULL,
    previous_status VARCHAR(20),
    new_status      VARCHAR(20),
    message         VARCHAR(255) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL
);

CREATE INDEX ix_audit_payment_created ON payment_audit_events (payment_id, created_at);
CREATE INDEX ix_audit_created_at      ON payment_audit_events (created_at DESC, id DESC);

CREATE TABLE idempotency_keys (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash    VARCHAR(64)  NOT NULL,
    payment_id      UUID         NOT NULL REFERENCES payments (id),
    created_at      TIMESTAMPTZ  NOT NULL,

    CONSTRAINT uq_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT uq_idempotency_payment UNIQUE (payment_id)
);
