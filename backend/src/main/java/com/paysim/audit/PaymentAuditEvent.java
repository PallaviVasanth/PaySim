package com.paysim.audit;

import com.paysim.payment.Payment;
import com.paysim.payment.PaymentStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.time.Instant;

/**
 * Append-only record of a significant payment event. Messages are generated by the server from
 * fixed templates and never contain request free-text, credentials or personal data.
 */
@Entity
@Table(name = "payment_audit_events")
public class PaymentAuditEvent {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "payment_id", nullable = false, updatable = false)
    private Payment payment;

    @Enumerated(EnumType.STRING)
    @Column(name = "event_type", nullable = false, length = 40, updatable = false)
    private AuditEventType eventType;

    @Enumerated(EnumType.STRING)
    @Column(name = "previous_status", length = 20, updatable = false)
    private PaymentStatus previousStatus;

    @Enumerated(EnumType.STRING)
    @Column(name = "new_status", length = 20, updatable = false)
    private PaymentStatus newStatus;

    @Column(nullable = false, length = 255, updatable = false)
    private String message;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    protected PaymentAuditEvent() {
        // required by JPA
    }

    private PaymentAuditEvent(Payment payment, AuditEventType type, PaymentStatus previous,
                              PaymentStatus next, String message) {
        this.payment = payment;
        this.eventType = type;
        this.previousStatus = previous;
        this.newStatus = next;
        this.message = message;
        this.createdAt = Instant.now();
    }

    public static PaymentAuditEvent created(Payment payment) {
        String message = payment.getStatus() == PaymentStatus.DECLINED
                ? "Payment created and declined (" + payment.getDeclineReason() + ")."
                : "Payment created and succeeded.";
        return new PaymentAuditEvent(payment, AuditEventType.PAYMENT_CREATED, null, payment.getStatus(), message);
    }

    public static PaymentAuditEvent refunded(Payment payment, PaymentStatus previous) {
        return new PaymentAuditEvent(payment, AuditEventType.PAYMENT_REFUNDED, previous,
                payment.getStatus(), "Payment fully refunded.");
    }

    public Long getId() { return id; }
    public AuditEventType getEventType() { return eventType; }
    public PaymentStatus getPreviousStatus() { return previousStatus; }
    public PaymentStatus getNewStatus() { return newStatus; }
    public String getMessage() { return message; }
    public Instant getCreatedAt() { return createdAt; }
}
